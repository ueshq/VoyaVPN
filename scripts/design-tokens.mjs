import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../packages/design-tokens/", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("tokens.json", root), "utf8"));
const kebab = (key) => key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const names = Object.keys(tokens.colors.light).sort();
if (JSON.stringify(names) !== JSON.stringify(Object.keys(tokens.colors.dark).sort())) {
  throw new Error("Design tokens: both themes must provide every color role");
}
for (const theme of ["light", "dark"]) {
  for (const [name, value] of Object.entries(tokens.colors[theme])) {
    if (!/^#[\da-f]{6}([\da-f]{2})?$/i.test(value)) throw new Error(`Invalid ${theme}.${name}: ${value}`);
  }
  if (Object.keys(tokens.shadow[theme]).join() !== Object.keys(tokens.shadow.light).join()) {
    throw new Error(`Incomplete ${theme} shadows`);
  }
}
function luminance(hex) {
  const channels = hex
    .slice(1)
    .match(/../g)
    .slice(0, 3)
    .map((c) => {
      const n = parseInt(c, 16) / 255;
      return n <= 0.04045 ? n / 12.92 : ((n + 0.055) / 1.055) ** 2.4;
    });
  return channels[0] * 0.2126 + channels[1] * 0.7152 + channels[2] * 0.0722;
}
for (const [theme, colors] of Object.entries(tokens.colors)) {
  const pairs = [
    ...["canvas", "card", "wash"].flatMap((bg) => ["ink", "muted"].map((fg) => [fg, bg, 4.5])),
    ["onPrimary", "ink", 4.5],
    ["onGreen", "green", 4.5],
    ["success", "successBg", 4.5],
    ["danger", "dangerBg", 4.5],
    ["warning", "warningBg", 4.5],
    ["onDanger", "dangerFill", 4.5],
    ["onWarning", "warningFill", 4.5],
    ["border", "card", 3],
    ["border", "canvas", 3],
    ["power", "dial", 4.5],
    ["border", "wash", 3],
    ["green", "card", 3],
    ["dangerFill", "card", 3],
  ];
  for (const [fg, bg, minimum] of pairs) {
    if (colors[fg]?.length !== 7 || colors[bg]?.length !== 7)
      throw new Error(`Contrast roles must be opaque: ${theme}.${fg}/${bg}`);
    const a = luminance(colors[fg]);
    const b = luminance(colors[bg]);
    const ratio = (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
    if (ratio < minimum) throw new Error(`${theme}.${fg}/${bg}: ${ratio.toFixed(2)} < ${minimum}`);
  }
}
const banner = "/* Generated by vp run generate design-tokens. Edit tokens.json, not this file. */\n";
function declarations(theme) {
  return (
    Object.entries(tokens.colors[theme])
      .map(([k, v]) => `  --voya-${kebab(k)}: ${v};`)
      .join("\n") +
    "\n" +
    Object.entries(tokens.shadow[theme])
      .map(([k, v]) => `  --voya-shadow-${k}: ${v};`)
      .join("\n")
  );
}
const dimensions = ["spacing", "radius", "control", "font", "motion", "type"]
  .flatMap((family) =>
    Object.entries(tokens[family]).map(
      ([key, value]) =>
        `  --voya-${family}-${kebab(key)}: ${value}${typeof value === "number" ? (family === "motion" ? "ms" : "px") : ""};`,
    ),
  )
  .join("\n");
const browser = banner + `:root {\n${dimensions}\n${declarations("light")}\n}\n.dark {\n${declarations("dark")}\n}\n`;
const system =
  banner +
  `:root {\n${dimensions}\n${declarations("light")}\n}\n@media (prefers-color-scheme: dark) {\n  :root {\n${declarations("dark")}\n  }\n}\n`;
// Native aliases are expanded to concrete values: Uniwind builds a theme map at compile time.
const aliases = {
  background: "canvas",
  foreground: "ink",
  surface: "card",
  "surface-foreground": "ink",
  "surface-secondary": "wash",
  "surface-secondary-foreground": "ink",
  "surface-tertiary": "wash",
  "surface-tertiary-foreground": "ink",
  overlay: "card",
  "overlay-foreground": "ink",
  backdrop: "blanket",
  muted: "muted",
  default: "wash",
  "default-foreground": "ink",
  accent: "ink",
  "accent-foreground": "onPrimary",
  "accent-soft": "wash",
  "accent-soft-foreground": "ink",
  "field-background": "card",
  "field-foreground": "ink",
  "field-placeholder": "muted",
  "field-border": "border",
  success: "success",
  "success-foreground": "onPrimary",
  warning: "warningFill",
  "warning-foreground": "onWarning",
  danger: "dangerFill",
  "danger-foreground": "onDanger",
  segment: "wash",
  "segment-foreground": "ink",
  border: "border",
  separator: "divider",
  focus: "ink",
  link: "ink",
  "voya-subtle": "muted",
  "voya-border-subtle": "divider",
  "voya-brand": "ink",
  "voya-brand-tint": "wash",
  "voya-connected": "success",
};
const native =
  banner +
  `@theme {\n${dimensions}\n  --radius: ${tokens.radius.control}px;\n  --field-radius: ${tokens.radius.control}px;\n  --field-border-width: 1px;\n}\n@layer theme {\n  :root {\n` +
  ["light", "dark"]
    .map(
      (theme) =>
        `    @variant ${theme} {\n${declarations(theme)}\n` +
        Object.entries(aliases)
          .map(([key, role]) => `      --${key}: ${tokens.colors[theme][role]};`)
          .join("\n") +
        `\n      --surface-shadow: ${tokens.shadow[theme].card};\n      --overlay-shadow: ${tokens.shadow[theme].overlay};\n      --field-shadow: 0 0 0 transparent;\n    }`,
    )
    .join("\n") +
  "\n  }\n}\n";
const output = {
  "browser.css": browser,
  "system.css": system,
  "native.css": native,
  "tokens.ts":
    "// Generated by vp run generate design-tokens. Edit tokens.json.\nexport const designTokens = " +
    JSON.stringify(tokens, null, 2) +
    " as const;\n",
};
const check = process.argv.includes("--check");
for (const [file, content] of Object.entries(output)) {
  const path = new URL(`src/${file}`, root);
  if (check) {
    if (readFileSync(path, "utf8") !== content)
      throw new Error(`Token output drift: ${fileURLToPath(path)}. Run vp run generate design-tokens.`);
  } else writeFileSync(path, content);
}
console.log(
  `Design tokens ${check ? "checked" : "generated"}: two complete themes, semantic contrast and four outputs.`,
);
