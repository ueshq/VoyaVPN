/** The marker position as percentages of the map box, or `null` for an unknown country. */
export function worldMapPosition(countryCode: string | null | undefined) {
  const coordinates: readonly [number, number] | undefined = countryCode
    ? COUNTRY_COORDINATES[countryCode.trim().toUpperCase()]
    : undefined;
  if (!coordinates) return null;
  const [lat, lon] = coordinates;
  return {
    left: ((535.8 + 2.912 * lon) / MAP_WIDTH) * 100,
    top: ((271.8 - 2.871 * lat) / MAP_HEIGHT) * 100,
  };
}
